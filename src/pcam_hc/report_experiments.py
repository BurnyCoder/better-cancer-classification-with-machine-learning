def render_summary() -> str:
    arms = {p.stem: json.loads(p.read_text()) for p in sorted((PATHS.results / "arms").glob("*.json"))}
    lad = _j("ladder.json") or {}
    steps = [json.loads(p.read_text()) for p in sorted((PATHS.results / "steps").glob("*.json"), key=lambda p: p.stat().st_mtime)]
    lines = ["# Summary of all experiments", "",
             "*Generated by `uv run python main.py report`; every number is read from `results/`.*", "",
             "## In plain words",
             "We take the best published AI model for spotting breast-cancer metastases in small lymph-node image patches "
             "(Hibou-L) and test, one pre-announced idea at a time, whether it can be made more accurate. "
             "Each idea is kept only if it clearly helps on training data split by slide *and* does not hurt on a separate "
             "validation set. The official test set is locked until the end so that we cannot fool ourselves.", "",
             "## Ladder so far", ""]
    if steps:
        lines += ["| Step | Incumbent | Best candidate | Adopted |", "|---|---|---|---|"]
        for s in steps:
            lines.append(f"| {s['step']} | `{s['incumbent']}` | `{s['winner']}` | {'yes' if s['adopted'] else 'no'} |")
        lines.append(f"\nBest Hibou-L pipeline: `{lad.get('hibou_incumbent', lad.get('incumbent'))}`. Frozen-feature incumbent "
                     f"(the input to the postponed S4 fusion): `{lad.get('incumbent')}`.\n")
    else:
        lines.append("No ladder step decided yet.\n")
    lines += ["## Networks", "",
              "| Network | Architecture | Training objective | Pretraining data | PCam OOF BA (CLS probe, this study) | Source |",
              "|---|---|---|---|---|---|"]
    for key, name, arch, obj, data, src in NETWORKS:
        arm = arms.get("S0_hibou_l_cls_linear" if key == "hibou_l" else f"S0_scan_{key}")
        ba = _ba(arm["oof"]["seed_avg"]) if arm and "oof" in arm else "pending"
        lines.append(f"| {name} | {arch} | {obj} | {data} | {ba} | {src} |")
    lines += ["", "## Experiments", ""]
    for p in sorted(EXP_DIR.glob("[0-9]*.md")):
        lines.append(f"- [{p.stem}](experiments/{p.name})")
    lines += ["", "## Glossary", ""] + [f"- **{t}**: {d}" for t, d in GLOSSARY]
    return "\n".join(lines) + "\n"


STEP_OF = {"S1_": "S1 representation", "S2_": "S2 head", "S3_": "S3 D4 TTA", "S3b_": "S3b label cleaning",
           "S5_": "S5 LoRA", "S5b_": "S5b weight space", "H4_": "H4 control (frozen, LoRA's augmentation)"}


def ladder_rows() -> list[dict]:
    """One row per trained ladder classifier with its paired difference from the original Hibou-L."""
    rows = []
    for p in sorted((PATHS.results / "comparisons").glob("*_vs_baseline.json")) if (PATHS.results / "comparisons").exists() else []:
        c = json.loads(p.read_text())
        arm = _arm(c["arm"])
        if arm is None:
            continue
        step = next((v for k, v in sorted(STEP_OF.items(), key=lambda kv: -len(kv[0])) if c["arm"].startswith(k)), "?")
        rows.append({"arm": c["arm"], "step": step, "description": arm.get("description", ""),
                     "oof": arm["oof"]["seed_avg"], "valid": arm["valid"]["seed_avg"], "cmp": c,
                     "subset": arm.get("oof_subset", "all train")})
    return rows


def ladder_table_md(rows: list[dict]) -> str:
    out = ["| Step | Classifier | OOF BA [95% CI] | Δ OOF vs original [95% CI] | sign-flip p | Valid BA | Δ valid vs original |",
           "|---|---|---|---|---|---|---|"]
    for r in rows:
        d, v = r["cmp"]["oof"], r["cmp"]["valid"]
        out.append(f"| {r['step']} | `{r['arm']}` | {_ba(r['oof'])} | {100 * d['delta_ba']:+.2f} pt [{100 * d['ci_ba'][0]:+.2f}, "
                   f"{100 * d['ci_ba'][1]:+.2f}] | {d['p_signflip']:.3g} | {r['valid']['ba']:.4f} | {100 * v['delta_ba']:+.2f} pt |")
    return "\n".join(out)


def _s2_learnings(steps: list[dict]) -> list[str]:
    """S2 learnings, every number read from the S2 arm and step files."""
    lr, step = _arm("S2_logreg"), next((s for s in steps if s["step"] == "S2_head"), None)
    if lr is None or step is None:
        return []
    path = ", ".join(f"C={c}: {ba:.4f}" for c, ba in lr["cv_ba_per_C"].items())
    v = step["comparisons"]["S2_logreg"]["valid"]
    lines = ["", "## S2 learnings",
             f"- **Logistic regression prefers the strongest regularisation on the grid.** The inner CV chose C = "
             f"{min(lr['chosen_C_per_fold'])} in all {len(lr['chosen_C_per_fold'])} outer folds. CV BA falls as C "
             f"grows to 1 and is flat beyond ({path}). The optimum probably lies below the pre-registered grid; the grid "
             "was not extended after seeing this, so S2 under-tests logistic regression (limitation).",
             f"- **The gate miss is within noise.** Logistic regression beat the original on OOF (Holm p "
             f"{step['holm_p']['S2_logreg']:.3g}), but its valid ΔBA was {100 * v['delta_ba']:+.2f} pt "
             f"[{100 * v['ci_ba'][0]:+.2f}, {100 * v['ci_ba'][1]:+.2f}]. The pre-registered gate needs ΔBA ≥ 0, so it "
             "was rejected; the valid data cannot tell the two heads apart."]
    if "S2_mlp" in step["comparisons"]:
        m = step["comparisons"]["S2_mlp"]
        lines.append(f"- **The MLP is clearly worse** (Δ OOF {100 * m['oof']['delta_ba']:+.2f} pt, Δ valid "
                     f"{100 * m['valid']['delta_ba']:+.2f} pt). Untested hypothesis, consistent with the C result: inside "
                     "CV there is no validation split for early stopping, so it trains the full 12,500 eva steps "
                     "(≈15 epochs) and overfits the training slides. The MLP was not tuned (fixed width 512, dropout 0.1).")
    return lines


def _pt(cm: dict, part: str) -> str:
    """Paired Δ BA with its 95% CI in points, e.g. '+0.77 pt [+0.27, +1.41]'."""
    x = cm[part]
    return f"{100 * x['delta_ba']:+.2f} pt [{100 * x['ci_ba'][0]:+.2f}, {100 * x['ci_ba'][1]:+.2f}]"


REFERENCE_ARMS = {"S3_no_tta_train64k"}  # S3's identity-view reference (the original recipe, 1 seed), not a change


def frozen_changes(rows: list[dict]) -> list[dict]:
    """Ladder rows that are frozen-feature changes (not LoRA, not the H4 control, not a reference arm)."""
    return [r for r in rows if not r["arm"].startswith(("S5", "H4")) and r["arm"] not in REFERENCE_ARMS]


def seed_offset() -> dict | None:
    """The single-seed effect on validation: the original recipe with seed 0 only (S3's identity-view arm)
    vs. the 5-seed original. One-seed linear-head arms carry this offset in their Δ valid vs. the original."""
    c, s0 = _j("comparisons/S3_no_tta_train64k_vs_baseline.json"), _arm("S0_hibou_l_cls_linear")
    return {"cmp": c, "valid_seed_sd": s0["valid"]["seed_sd"]["ba"], "oof_seed_sd": s0["oof"]["seed_sd"]["ba"]} if c and s0 else None


def ladder_findings() -> list[str]:
    """Headline findings of releases 2+, one sentence each, every number from results/. Shared by the
    paper's abstract and conclusion and the README highlights."""
    rows, out = ladder_rows(), []
    if not rows:
        return out
    steps = [json.loads(p.read_text()) for p in sorted((PATHS.results / "steps").glob("*.json"), key=lambda p: p.stat().st_mtime)]
    adopted = [s["step"] for s in steps if s["adopted"]]
    out.append(f"Of {len(steps)} decided ladder steps, {len(adopted)} were adopted ({', '.join(f'`{s}`' for s in adopted) or 'none'}).")
    frozen = frozen_changes(rows)
    if frozen:
        top = max(frozen, key=lambda r: r["cmp"]["valid"]["delta_ba"])
        sig = any(r["cmp"]["valid"]["ci_ba"][0] > 0 for r in frozen)
        out.append(f"{'At least one' if sig else 'No'} frozen-feature classifier has a validation gain whose 95% CI excludes zero "
                   f"(largest: {_pt(top['cmp'], 'valid')}, `{top['arm']}`).")
    s0, s5, s5c = _arm("S0_hibou_l_cls_linear"), _arm("S5_lora"), _j("comparisons/S5_lora_vs_baseline.json")
    if s5 and s5c:
        out.append(f"LoRA fine-tuning raises validation BA from {s0['valid']['seed_avg']['ba']:.4f} to {s5['valid']['seed_avg']['ba']:.4f} "
                   f"(paired Δ {_pt(s5c, 'valid')}).")
    if h4c := _j("comparisons/S5_lora_vs_H4_aug_control.json"):
        out.append(f"LoRA also beats a frozen head trained on the same images with the same augmentation (Δ valid {_pt(h4c, 'valid')}).")
    models = [_arm(n) for n in CONTROL_MODELS]
    if all(models):
        out.append(f"With Hibou-L's architecture, natural-image weights reach {models[0]['oof']['seed_avg']['ba']:.3f} and random weights "
                   f"{models[1]['oof']['seed_avg']['ba']:.3f} OOF BA, against {s0['oof']['seed_avg']['ba']:.3f} for Hibou-L.")
    return out


