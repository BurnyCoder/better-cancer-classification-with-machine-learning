"""Paper generator: Typst source filled from results/*.json, compiled to reports/paper/paper.pdf.

Global context: the user's rules require a paper with every number traceable to a results file and
regenerated by one command (`main.py report`). The text below is a fixed template; numbers, tables
and figures come from results/ and reports/figures/. The paper grows with each release milestone:
sections whose results do not exist yet say so explicitly instead of being left out.
"""

import json

from pcam_hc.config import PATHS, PROJECT_ROOT

PAPER_DIR = PROJECT_ROOT / "reports" / "paper"


def _j(name):
    p = PATHS.results / name
    return json.loads(p.read_text()) if p.exists() else None


def _ba(b: dict) -> str:
    return f"{b['ba']:.4f} [{b['ci_ba'][0]:.4f}, {b['ci_ba'][1]:.4f}]"


def _cell(x) -> str:
    return "[" + str(x).replace("[", "\\[").replace("]", "\\]").replace("#", "\\#").replace("*", "\\*").replace("_", "\\_") + "]"


def _table(header: list, rows: list) -> str:
    cells = ", ".join(_cell(h) for h in header) + ",\n" + ",\n".join(", ".join(_cell(c) for c in r) for r in rows)
    return (f"#table(columns: {len(header)}, stroke: 0.4pt + luma(200), inset: 4pt, align: left,\n"
            f"  table.header({', '.join('[*' + str(h) + '*]' for h in header)}),\n  " +
            ",\n  ".join(", ".join(_cell(c) for c in r) for r in rows) + ")")


