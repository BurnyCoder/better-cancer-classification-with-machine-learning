    w_val = s0["valid"]["seed_avg"]["ci_ba"][1] - s0["valid"]["seed_avg"]["ci_ba"][0]
    w_oof = s0["oof"]["seed_avg"]["ci_ba"][1] - s0["oof"]["seed_avg"]["ci_ba"][0]

