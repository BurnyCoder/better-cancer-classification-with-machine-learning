def compile_paper() -> str | None:
    import typst

    src = build_paper()
    if src is None:
        return None
    PAPER_DIR.mkdir(parents=True, exist_ok=True)
    (PAPER_DIR / "paper.typ").write_text(src, encoding="utf-8")
    typst.compile(str(PAPER_DIR / "paper.typ"), output=str(PAPER_DIR / "paper.pdf"), root=str(PROJECT_ROOT))
    return str(PAPER_DIR / "paper.pdf")
